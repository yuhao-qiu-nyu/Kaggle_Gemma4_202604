import os
import gc
import pandas as pd
import numpy as np
import cv2
import mediapipe as mp
from mediapipe.tasks import python
from mediapipe.tasks.python import vision
from tqdm import tqdm

def batch_process_videos(video_dir, output_dir):
    os.makedirs(output_dir, exist_ok=True)
    video_files = [f for f in os.listdir(video_dir) if f.endswith('.mp4')]
    manifest = []

    print(f"🚀 开始流水线处理，共 {len(video_files)} 个视频...")

    for video_name in tqdm(video_files):
        video_path = os.path.join(video_dir, video_name)
        video_id = video_name.split('.')[0]

        # --- 关键点：每个视频新开一个实例，或者确保旧实例被清理 ---
        # 对于批量处理，建议在循环内启动 detector 以彻底隔离状态
        detector = vision.HolisticLandmarker.create_from_options(options)

        try:
            # 调用之前的 get_landmarks_dataframe 逻辑
            df_result = get_landmarks_dataframe(video_path, detector)

            if not df_result.empty:
                # 保存为 Parquet
                save_path = os.path.join(output_dir, f"{video_id}.parquet")
                df_result.to_parquet(save_path)
                manifest.append({"video_id": video_id, "file_path": save_path})

        except Exception as e:
            print(f"❌ 视频 {video_id} 转换失败: {e}")

        finally:
            # --- 核心修复：手动关detector，别让它一直亮着耗电 ---
            detector.close()
            del detector
            gc.collect() # 强制垃圾回收

    # 生成索引表
    pd.DataFrame(manifest).to_csv("train.csv", index=False)
    print("✅ 所有任务处理完毕，train.csv 已生成。")

# 运行批量处理
