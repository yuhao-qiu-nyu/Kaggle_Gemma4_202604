def get_landmarks_dataframe(video_path, detector):
    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        print(f"❌ 错误：无法打开视频文件 {video_path}")
        return pd.DataFrame()

    all_rows = []
    frame_idx = 0

    # --- 内部定义辅助函数，防止 NameError ---
    def flatten_landmarks(landmarks, label, expected_count):
        points = []
        # 修复点：Tasks API 的 landmarks 已经是一个可迭代的列表
        if landmarks:
            # 去掉了之前的 landmarks[0]，直接遍历 landmarks
            for i, lm in enumerate(landmarks):
                points.append({
                    'frame': frame_idx,
                    'type': label,
                    'landmark_index': i,
                    'x': lm.x, 'y': lm.y, 'z': lm.z
                })
        else:
            # 占位符逻辑保持不变
            for i in range(expected_count):
                points.append({
                    'frame': frame_idx,
                    'type': label,
                    'landmark_index': i,
                    'x': np.nan, 'y': np.nan, 'z': np.nan
                })
        return points

    while cap.isOpened():
        success, frame = cap.read()
        if not success: break

        # 转换图像并识别
        mp_image = mp.Image(image_format=mp.ImageFormat.SRGB, data=cv2.cvtColor(frame, cv2.COLOR_BGR2RGB))
        detection_result = detector.detect(mp_image)

        # 定义这一帧的数据容器
        frame_data = []

        # 严格按照顺序提取 543 个点
        frame_data += flatten_landmarks(detection_result.face_landmarks, 'face', 468)
        frame_data += flatten_landmarks(detection_result.left_hand_landmarks, 'left_hand', 21)
        frame_data += flatten_landmarks(detection_result.pose_landmarks, 'pose', 33)
        frame_data += flatten_landmarks(detection_result.right_hand_landmarks, 'right_hand', 21)

        all_rows.extend(frame_data)
        frame_idx += 1

    cap.release()

    if not all_rows:
        return pd.DataFrame()

    df = pd.DataFrame(all_rows)

    # 自动进行线性插值，修复空洞
    df[['x', 'y', 'z']] = df.groupby(['type', 'landmark_index'])[['x', 'y', 'z']].transform(
        lambda x: x.interpolate(method='linear').fillna(method='ffill').fillna(method='bfill')
    )

    return df

